    #[test]
    fn test_mds_partial_t8_unit() {
        // [1,0,0,0,0,0,0,0]: sum=1, result[i] = 1 + 0*diag[i] = 1 for all
        let state = {
            let mut s = [0u64; WIDTH_T8];
            s[0] = 1;
            s
        };
        let result = mds_multiply_partial_t8(&state);
        // sum = 1, diag_contrib = state[i] * MAT_DIAG8_M_1[i] = 0 for all i>0
        assert_eq!(result[0], 1); // 1 + 1*0 = 1
        assert_eq!(result[1], 1); // 1 + 0*1 = 1
        for &r in &result {
            assert_eq!(r, 1);
        }
    }

