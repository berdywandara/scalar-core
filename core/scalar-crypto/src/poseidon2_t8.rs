// ── MDS Matrix M_E for t=8 — HorizenLabs reference ───────────────────────────
// Circulant matrix for t=8 over Goldilocks field.
// Reference: HorizenLabs poseidon2 repository, Goldilocks t=8 parameters.

const MATRIX_FULL_T8: [[u64; WIDTH_T8]; WIDTH_T8] = [
    [5, 7, 1, 3, 5, 7, 1, 3],
    [3, 5, 7, 1, 3, 5, 7, 1],
    [1, 3, 5, 7, 1, 3, 5, 7],
    [7, 1, 3, 5, 7, 1, 3, 5],
    [5, 7, 1, 3, 5, 7, 1, 3],
    [3, 5, 7, 1, 3, 5, 7, 1],
    [1, 3, 5, 7, 1, 3, 5, 7],
    [7, 1, 3, 5, 7, 1, 3, 5],
];

// ── Internal Matrix M_I diagonal for t=8 ─────────────────────────────────────
// diag[i] = MAT_DIAG8_M_1[i] + 1, stored as (diag - 1).
// Reference: HorizenLabs poseidon2, Goldilocks t=8.

const MAT_DIAG8_M_1: [u64; WIDTH_T8] = [0, 1, 2, 3, 4, 5, 6, 7];

// ── S-box ─────────────────────────────────────────────────────────────────────

#[inline]
fn sbox_t8(x: u64) -> u64 {
    // x^7 mod p — same as t=4, alpha=7 is OSSIFIED.
    let x2 = field_mul(x, x);
    let x4 = field_mul(x2, x2);
    let x6 = field_mul(x4, x2);
    field_mul(x6, x)
}

// ── Linear Layers ─────────────────────────────────────────────────────────────

/// M_E multiplication for t=8 full rounds.
fn mds_multiply_full_t8(state: &[u64; WIDTH_T8]) -> [u64; WIDTH_T8] {
    let mut result = [0u64; WIDTH_T8];
    for i in 0..WIDTH_T8 {
        let mut acc = 0u64;
        for j in 0..WIDTH_T8 {
            let term = field_mul(MATRIX_FULL_T8[i][j], state[j]);
            acc = field_add(acc, term);
        }
        result[i] = acc;
    }
    result
}

/// M_I multiplication for t=8 partial rounds.
/// result[i] = sum(state) + state[i] * MAT_DIAG8_M_1[i]
#[inline]
fn mds_multiply_partial_t8(state: &[u64; WIDTH_T8]) -> [u64; WIDTH_T8] {
    let sum = state.iter().fold(0u64, |acc, &x| field_add(acc, x));
    let mut result = [0u64; WIDTH_T8];
    for i in 0..WIDTH_T8 {
        let diag_contrib = field_mul(state[i], MAT_DIAG8_M_1[i]);
        result[i] = field_add(sum, diag_contrib);
    }
    result
}

// ── Poseidon2 t=8 Permutation ─────────────────────────────────────────────────

/// Poseidon2 permutation for state width=8 Goldilocks. Decision D-008. OSSIFIED.
///
/// Structure: M_E → R_F/2 full rounds → R_P partial rounds → R_F/2 full rounds.
pub fn poseidon2_permutation_t8(state: &mut [u64; WIDTH_T8]) {
    let half_full = FULL_ROUNDS_T8 / 2; // 4

    // Initial linear layer (M_E)
    *state = mds_multiply_full_t8(state);

    // Full rounds first half (rounds 0..4)
    for rc in ROUND_CONSTANTS_T8.iter().take(half_full) {
        for (s, &c) in state.iter_mut().zip(rc.iter()) {
            *s = field_add(*s, c);
        }
        for s in state.iter_mut() {
            *s = sbox_t8(*s);
        }
        *state = mds_multiply_full_t8(state);
    }

    // Partial rounds (rounds 4..26): S-box only on state[0], M_I
    for rc in ROUND_CONSTANTS_T8
        .iter()
        .skip(half_full)
        .take(PARTIAL_ROUNDS_T8)
    {
        for (s, &c) in state.iter_mut().zip(rc.iter()) {
            *s = field_add(*s, c);
        }
        state[0] = sbox_t8(state[0]);
        *state = mds_multiply_partial_t8(state);
    }

    // Full rounds second half (rounds 26..30)
    for rc in ROUND_CONSTANTS_T8
        .iter()
        .skip(half_full + PARTIAL_ROUNDS_T8)
        .take(half_full)
    {
        for (s, &c) in state.iter_mut().zip(rc.iter()) {
            *s = field_add(*s, c);
        }
        for s in state.iter_mut() {
            *s = sbox_t8(*s);
        }
        *state = mds_multiply_full_t8(state);
    }
}

// ── Poseidon2 t=8 Hasher — Sponge Construction ───────────────────────────────

/// Poseidon2 t=8 sponge hasher. Rate=4, Capacity=4. Decision D-008.
pub struct Poseidon2T8Hasher;

impl Poseidon2T8Hasher {
    /// Hash slice of Goldilocks field elements with 10* padding. Decision D-008.
    pub fn hash(input: &[u64]) -> [u64; 8] {
        let mut state = [0u64; WIDTH_T8];

        let mut padded: Vec<u64> = input.iter().map(|&x| field_reduce(x)).collect();
        padded.push(1u64);
        while !padded.len().is_multiple_of(RATE_T8) {
            padded.push(0u64);
        }
        let last = padded.len() - 1;
        padded[last] = field_add(padded[last], 1u64);

        for chunk in padded.chunks(RATE_T8) {
            for (i, &elem) in chunk.iter().enumerate() {
                state[i] = field_add(state[i], elem);
            }
            poseidon2_permutation_t8(&mut state);
        }

        state
    }

    /// Hash field elements, return first 4 elements (256-bit output).
    pub fn hash_to_4(input: &[u64]) -> [u64; 4] {
        let full = Self::hash(input);
        [full[0], full[1], full[2], full[3]]
    }

    /// Hash bytes to 8 field elements. Decision D-008.
    pub fn hash_bytes(input: &[u8]) -> [u64; 8] {
        let mut field_elems: Vec<u64> = input
            .chunks(8)
            .map(|chunk| {
                let mut buf = [0u8; 8];
                buf[..chunk.len()].copy_from_slice(chunk);
                field_reduce(u64::from_le_bytes(buf))
            })
            .collect();
        if field_elems.is_empty() {
            field_elems.push(0);
        }
        Self::hash(&field_elems)
    }
}

/// Convert 8 Goldilocks field elements to 64 bytes.
pub fn field8_to_bytes(elems: &[u64; 8]) -> [u8; 64] {
    let mut out = [0u8; 64];
    for (i, &e) in elems.iter().enumerate() {
        out[i * 8..(i + 1) * 8].copy_from_slice(&e.to_le_bytes());
    }
    out
}

/// Convert first 4 of 8 field elements to 32 bytes.
pub fn field8_to_bytes32(elems: &[u64; 8]) -> [u8; 32] {
    let mut out = [0u8; 32];
    for (i, &e) in elems.iter().enumerate().take(4) {
        out[i * 8..(i + 1) * 8].copy_from_slice(&e.to_le_bytes());
    }
    out
}

