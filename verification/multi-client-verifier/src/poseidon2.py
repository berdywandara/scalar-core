# ── Goldilocks prime ──────────────────────────────────────────────────────────
P = (1 << 64) - (1 << 32) + 1  # 0xFFFFFFFF00000001

# ── Field arithmetic ──────────────────────────────────────────────────────────

def gl_add(a, b):
    return (a + b) % P

def gl_mul(a, b):
    return (a * b) % P

def gl_pow7(a):
    """S-box: x -> x^7 (alpha=7, OSSIFIED)."""
    a2 = gl_mul(a, a)
    a4 = gl_mul(a2, a2)
    return gl_mul(gl_mul(a4, a2), a)

# ── External MDS — apply_mat4 + mds_light_permutation ────────────────────────
# Source: p3-poseidon2 v0.5.3 external.rs
#
# apply_mat4 multiplies by the circulant matrix with first row [2,3,1,1]:
#   row 0: [2, 3, 1, 1]
#   row 1: [1, 2, 3, 1]
#   row 2: [1, 1, 2, 3]
#   row 3: [3, 1, 1, 2]
#
# mds_light_permutation for width-8:
#   1. Apply apply_mat4 to each group of 4 elements independently.
#   2. sums[k] = state[k] + state[k+4]  (sum across groups)
#   3. state[i] += sums[i % 4]

def _apply_mat4(s):
    """p3-poseidon2 apply_mat4 — circulant matrix [2,3,1,1]."""
    t01   = gl_add(s[0], s[1])
    t23   = gl_add(s[2], s[3])
    t0123 = gl_add(t01, t23)
    t01123 = gl_add(t0123, s[1])            # t0123 + x[1]
    t01233 = gl_add(t0123, s[3])            # t0123 + x[3]
    # Overwrite x[0] and x[2] after x[1] and x[3] (order matters in Rust)
    r3 = gl_add(t01233, gl_add(s[0], s[0])) # 3x0+x1+x2+2x3
    r1 = gl_add(t01123, gl_add(s[2], s[2])) # x0+2x1+3x2+x3
    r0 = gl_add(t01123, t01)                 # 2x0+3x1+x2+x3
    r2 = gl_add(t01233, t23)                 # x0+x1+2x2+3x3
    return [r0, r1, r2, r3]

def _external_mds_8(state):
    """mds_light_permutation(state, MDSMat4) for width=8."""
    # Step 1: apply apply_mat4 to each group of 4
    left  = _apply_mat4(state[0:4])
    right = _apply_mat4(state[4:8])
    s = left + right
    # Step 2: sums[k] = state[k] + state[k+4]
    sums = [gl_add(s[k], s[k + 4]) for k in range(4)]
    # Step 3: state[i] += sums[i % 4]
    return [gl_add(s[i], sums[i % 4]) for i in range(8)]

