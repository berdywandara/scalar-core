def _internal_mds_8(state):
    """Internal MDS: state[i] = state[i] * DIAG[i] + sum(state)."""
    total = 0
    for x in state:
        total = gl_add(total, x)
    return [gl_add(gl_mul(state[i], _DIAG_8[i]), total) for i in range(8)]

